    Case("alac24-3ch-48000", "m4a", 24, 48_000, 3, 0x0007, "3.0", 521),
    Case("alac24-4ch-48000", "mp4", 24, 48_000, 4, 0x0107, "4.0", 523),
    Case("alac24-5ch-48000", "m4a", 24, 48_000, 5, 0x0607, "5.0", 527),
