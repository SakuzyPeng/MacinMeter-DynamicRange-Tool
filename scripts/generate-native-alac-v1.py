def sha256(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def script_sha256() -> str:
    return sha256(Path(__file__).read_bytes())


def ffmpeg_identity(executable: str) -> dict[str, str]:
    completed = subprocess.run(
        [executable, "-version"],
        check=True,
        capture_output=True,
        text=True,
    )
    lines = completed.stdout.splitlines()
    if not lines or not lines[0].startswith(f"ffmpeg version {FFMPEG_VERSION}"):
        observed = lines[0] if lines else "<no output>"
        raise SystemExit(
            f"native-alac-v1 requires ffmpeg {FFMPEG_VERSION}; observed: {observed}"
        )
    configuration = next(
        (line for line in lines if line.startswith("configuration:")), ""
    )
    return {
        "tool": "ffmpeg",
        "version": FFMPEG_VERSION,
        "versionLine": lines[0],
        "configurationSha256": sha256(configuration.encode("utf-8")),
    }


def pcm_values(case: Case) -> list[int]:
    peak = (1 << (case.bits - 1)) - 1
    span = peak * 2 + 1
    values: list[int] = []
    for frame in range(case.frames):
        for channel in range(case.channels):
            raw = (
                frame * (7_919 + channel * 131)
                + channel * 104_729
                + (frame // 17) * 65_537
            ) % span
            value = raw - peak
            if frame == channel:
                value = peak
            elif frame == channel + case.channels:
                value = -peak
            elif frame % 257 == 0:
                value = 0
            values.append(value)
    return values


def pack_pcm(values: list[int], bits: int) -> bytes:
    if bits == 16:
        return b"".join(struct.pack("<h", value) for value in values)
    if bits == 24:
        return b"".join((value & 0xFF_FFFF).to_bytes(3, "little") for value in values)
    raise AssertionError(bits)


def riff_chunk(kind: bytes, payload: bytes) -> bytes:
    padding = b"\0" if len(payload) % 2 else b""
    return kind + struct.pack("<I", len(payload)) + payload + padding


def wave_bytes(case: Case, values: list[int]) -> bytes:
    bytes_per_sample = case.bits // 8
    block_align = case.channels * bytes_per_sample
    byte_rate = case.sample_rate * block_align
    if case.channels <= 2:
        fmt = struct.pack(
            "<HHIIHH",
            1,
            case.channels,
            case.sample_rate,
            byte_rate,
            block_align,
            case.bits,
        )
    else:
        fmt = struct.pack(
            "<HHIIHHHHI",
            0xFFFE,
            case.channels,
            case.sample_rate,
            byte_rate,
            block_align,
            case.bits,
            22,
            case.bits,
            case.channel_mask,
        ) + PCM_GUID
    body = b"WAVE" + riff_chunk(b"fmt ", fmt) + riff_chunk(
        b"data", pack_pcm(values, case.bits)
    )
    return b"RIFF" + struct.pack("<I", len(body)) + body


def normalized_pcm_sha256(values: list[int], bits: int) -> str:
    divisor = float(1 << (bits - 1))
    digest = hashlib.sha256()
    for value in values:
        digest.update(struct.pack("<d", value / divisor))
    return digest.hexdigest()


def encode_alac(
    executable: str,
    case: Case,
    wave_path: Path,
    output_path: Path,
) -> list[str]:
    command = [
        executable,
        "-y",
        "-hide_banner",
        "-loglevel",
        "error",
        "-fflags",
        "+bitexact",
        "-i",
        str(wave_path),
        "-map_metadata",
        "-1",
        "-vn",
        "-c:a",
        "alac",
        "-compression_level",
        "2",
        "-flags:a",
        "+bitexact",
        "-channel_layout:a",
        case.channel_layout,
    ]
    if case.faststart:
        command.extend(["-movflags", "+faststart"])
    if case.title is not None:
        command.extend(["-metadata", f"title={case.title}"])
    command.extend(["-f", "ipod" if case.extension == "m4a" else "mp4", str(output_path)])
    subprocess.run(command, check=True)
    recorded = ["ffmpeg", *command[1:-1], f"<output>.{case.extension}"]
    return normalize_recorded_paths(recorded, output_path.parent)


def run_negative_command(
    executable: str, arguments: list[str], output_path: Path
) -> list[str]:
    command = [
        executable,
        "-y",
        "-hide_banner",
        "-loglevel",
        "error",
        *arguments,
        str(output_path),
    ]
    subprocess.run(command, check=True)
    recorded = ["ffmpeg", *command[1:-1], f"<output>{output_path.suffix}"]
    return normalize_recorded_paths(recorded, output_path.parent)


def normalize_recorded_paths(command: list[str], corpus: Path) -> list[str]:
    prefix = f"{corpus}/"
    return [
        f"<corpus>/{Path(argument).name}"
        if argument.startswith(prefix)
        else argument
        for argument in command
    ]


def find_box_type(data: bytes, kind: bytes) -> int:
    position = data.find(kind)
    while position >= 4:
        size = struct.unpack(">I", data[position - 4 : position])[0]
        if size == 1:
            if position + 12 <= len(data):
                extended = struct.unpack(">Q", data[position + 4 : position + 12])[0]
                if extended >= 16 and position - 4 + extended <= len(data):
                    return position
        elif size >= 8 and position - 4 + size <= len(data):
            return position
        position = data.find(kind, position + 1)
    raise ValueError(f"missing valid {kind!r} box")


def inspect_generated_alac(data: bytes) -> dict[str, object]:
    top_level_boxes: list[dict[str, object]] = []
    position = 0
    while position < len(data):
        if position + 8 > len(data):
            raise ValueError("truncated top-level box")
        size32 = struct.unpack(">I", data[position : position + 4])[0]
        kind = data[position + 4 : position + 8].decode("ascii")
        if size32 == 1:
            if position + 16 > len(data):
                raise ValueError("truncated extended top-level box")
            size = struct.unpack(">Q", data[position + 8 : position + 16])[0]
            size_encoding = 64
        else:
            size = size32
            size_encoding = 32
        if size < (16 if size_encoding == 64 else 8) or position + size > len(data):
            raise ValueError(f"invalid top-level {kind} box size")
        top_level_boxes.append(
            {
                "type": kind,
                "offset": position,
                "sizeBytes": size,
                "sizeEncodingBits": size_encoding,
            }
        )
        position += size

    alac_types: list[int] = []
    search = 0
    while True:
        found = data.find(b"alac", search)
        if found < 0:
            break
        if found >= 4:
            size = struct.unpack(">I", data[found - 4 : found])[0]
            if size >= 8 and found - 4 + size <= len(data):
                alac_types.append(found)
        search = found + 1
    if len(alac_types) != 2:
        raise ValueError(f"expected two ALAC box identifiers, found {len(alac_types)}")
    sample_entry_type, config_type = alac_types
    config_size = struct.unpack(">I", data[config_type - 4 : config_type])[0]
    if data[config_type + 4 : config_type + 8] != b"\0\0\0\0":
        raise ValueError("generated ALAC config full-box field is nonzero")
    cookie = data[config_type + 8 : config_type - 4 + config_size]
    if len(cookie) not in (24, 48):
        raise ValueError(f"unexpected ALAC cookie length {len(cookie)}")

    mdhd = find_box_type(data, b"mdhd")
    mdhd_version = data[mdhd + 4]
    if mdhd_version == 0:
        mdhd_timescale = struct.unpack(">I", data[mdhd + 16 : mdhd + 20])[0]
        mdhd_duration = struct.unpack(">I", data[mdhd + 20 : mdhd + 24])[0]
    elif mdhd_version == 1:
        mdhd_timescale = struct.unpack(">I", data[mdhd + 24 : mdhd + 28])[0]
        mdhd_duration = struct.unpack(">Q", data[mdhd + 28 : mdhd + 36])[0]
    else:
        raise ValueError(f"unexpected mdhd version {mdhd_version}")

    stts = find_box_type(data, b"stts")
    stts_entry_count = struct.unpack(">I", data[stts + 8 : stts + 12])[0]
    stts_packets = 0
    stts_frames = 0
    for entry in range(stts_entry_count):
        offset = stts + 12 + entry * 8
        packet_count, packet_frames = struct.unpack(">II", data[offset : offset + 8])
        stts_packets += packet_count
        stts_frames += packet_count * packet_frames

    stsz = find_box_type(data, b"stsz")
    stsz_default_size = struct.unpack(">I", data[stsz + 8 : stsz + 12])[0]
    stsz_sample_count = struct.unpack(">I", data[stsz + 12 : stsz + 16])[0]

    layout: dict[str, object] = {"mode": "implicit_standard_by_channel_count"}
    if len(cookie) == 48:
        layout = {
            "mode": "explicit_standard_tag",
            "tag": f"0x{struct.unpack('>I', cookie[36:40])[0]:08x}",
        }
    return {
        "topLevelBoxes": top_level_boxes,
        "sampleEntry": {
            "type": "alac",
            "channels": struct.unpack(">H", data[sample_entry_type + 20 : sample_entry_type + 22])[0],
            "sampleRateFixed16_16": f"0x{struct.unpack('>I', data[sample_entry_type + 28 : sample_entry_type + 32])[0]:08x}",
        },
        "cookie": {
            "lengthBytes": len(cookie),
            "frameLength": struct.unpack(">I", cookie[0:4])[0],
            "compatibleVersion": cookie[4],
            "bitDepth": cookie[5],
            "channels": cookie[9],
            "sampleRate": struct.unpack(">I", cookie[20:24])[0],
            "channelLayout": layout,
        },
        "mediaHeader": {
            "version": mdhd_version,
            "timescale": mdhd_timescale,
            "durationFrames": mdhd_duration,
        },
        "sampleTables": {
            "sttsEntryCount": stts_entry_count,
            "sttsPacketCount": stts_packets,
            "sttsFrameCount": stts_frames,
            "stszDefaultSampleSize": stsz_default_size,
            "stszSampleCount": stsz_sample_count,
        },
    }


