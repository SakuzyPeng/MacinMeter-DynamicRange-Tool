def build_corpus(destination: Path, executable: str) -> dict[str, object]:
    destination.mkdir(parents=True, exist_ok=True)
    (destination / "README.md").write_text(README, encoding="utf-8")
    encoder = ffmpeg_identity(executable)
    fixtures: list[dict[str, object]] = []
    for case in CASES:
        values = pcm_values(case)
        wave_name = f"{case.stem}-twin.wav"
        alac_name = f"{case.stem}.{case.extension}"
        wave_path = destination / wave_name
        alac_path = destination / alac_name
        wave_path.write_bytes(wave_bytes(case, values))
        command = encode_alac(executable, case, wave_path, alac_path)
        alac_bytes = alac_path.read_bytes()
        structure = inspect_generated_alac(alac_bytes)
        cookie = structure["cookie"]
        media_header = structure["mediaHeader"]
        sample_tables = structure["sampleTables"]
        if cookie != {
            "lengthBytes": 24,
            "frameLength": 4096,
            "compatibleVersion": 0,
            "bitDepth": case.bits,
            "channels": case.channels,
            "sampleRate": case.sample_rate,
            "channelLayout": {"mode": "implicit_standard_by_channel_count"},
        }:
            raise ValueError(f"{alac_name}: unexpected ALAC cookie {cookie}")
        if (
            media_header["timescale"] != case.sample_rate
            or media_header["durationFrames"] != case.frames
        ):
            raise ValueError(f"{alac_name}: mdhd geometry disagrees with generated PCM")
        if (
            sample_tables["sttsFrameCount"] != case.frames
            or sample_tables["sttsPacketCount"]
            != sample_tables["stszSampleCount"]
        ):
            raise ValueError(f"{alac_name}: generated ALAC sample tables disagree")
        pcm_hash = normalized_pcm_sha256(values, case.bits)
        common = {
            "sampleRate": case.sample_rate,
            "channels": case.channels,
            "bitsPerSample": case.bits,
            "frames": case.frames,
            "channelMask": f"0x{case.channel_mask:08x}",
            "channelLayout": case.channel_layout,
            "normalizedInterleavedF64LeSha256": pcm_hash,
        }
        fixtures.append(
            {
                "path": wave_name,
                "sha256": sha256(wave_path.read_bytes()),
                "kind": "wave_twin",
                "twin": alac_name,
                **common,
            }
        )
        fixtures.append(
            {
                "path": alac_name,
                "sha256": sha256(alac_bytes),
                "kind": "alac",
                "container": "mp4",
                "codec": "alac",
                "compatibleVersion": 0,
                "frameLength": 4096,
                "faststart": case.faststart,
                "twin": wave_name,
                "encoderCommand": command,
                "isoBmff": structure,
                **common,
            }
        )
    route_negative_sources = build_route_negative_sources(destination, executable)
    manifest: dict[str, object] = {
        "schemaVersion": 1,
        "corpus": "native-alac-v1",
        "generator": {
            "path": "scripts/generate-native-alac-v1.py",
            "sha256": script_sha256(),
            "commands": [
                "python3 scripts/generate-native-alac-v1.py",
                "python3 scripts/generate-native-alac-v1.py --check",
            ],
            "externalToolsRequiredForRegeneration": True,
            "normalTestsRequireExternalTools": False,
        },
        "encoder": encoder,
        "provenance": {
            "kind": "deterministically_generated",
            "copyrightedAudio": False,
            "license": "MIT",
        },
        "fixtures": fixtures,
        "routeNegativeSources": route_negative_sources,
    }
    (destination / "manifest.json").write_text(
        json.dumps(manifest, indent=2, sort_keys=True) + "\n", encoding="utf-8"
    )
    return manifest


def compare_directories(expected: Path, actual: Path) -> None:
    expected_files = sorted(
        path.relative_to(expected) for path in expected.rglob("*") if path.is_file()
    )
    actual_files = sorted(
        path.relative_to(actual) for path in actual.rglob("*") if path.is_file()
    )
    if expected_files != actual_files:
        raise SystemExit(
            "committed native ALAC fixture paths differ from the pinned generator"
        )
    changed = [
        str(path)
        for path in expected_files
        if (expected / path).read_bytes() != (actual / path).read_bytes()
    ]
    if changed:
        raise SystemExit(
            "committed native ALAC fixtures differ from the pinned generator: "
            + ", ".join(changed)
        )


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--ffmpeg", default=shutil.which("ffmpeg"))
    args = parser.parse_args()
    if not args.ffmpeg:
        parser.error("ffmpeg is required to regenerate native-alac-v1")

    if args.check:
        if not OUTPUT.is_dir():
            raise SystemExit(f"committed corpus is missing: {OUTPUT}")
        with tempfile.TemporaryDirectory(prefix="macinmeter-native-alac-") as directory:
            generated = Path(directory)
            build_corpus(generated, args.ffmpeg)
            compare_directories(OUTPUT, generated)
        print("native-alac-v1 matches the pinned generator")
        return 0

    with tempfile.TemporaryDirectory(prefix="macinmeter-native-alac-") as directory:
        generated = Path(directory)
        build_corpus(generated, args.ffmpeg)
        OUTPUT.mkdir(parents=True, exist_ok=True)
        for existing in OUTPUT.iterdir():
            if existing.is_file():
                existing.unlink()
        for source in generated.iterdir():
            shutil.copy2(source, OUTPUT / source.name)
    print(f"generated {OUTPUT.relative_to(ROOT)}")
    return 0


